import { useEffect, useState } from "react";
import Charts from "./Charts";
import Baselines from "./Baselines";
import FLProcess from "./FLProcess";

const API = (import.meta.env.VITE_API_URL || "http://localhost:8000") + "/api";

const initial = {
  age: 55, sex: 1, cp: 4, trestbps: 140, chol: 240, fbs: 0,
  restecg: 0, thalach: 130, exang: 1, oldpeak: 1.5, slope: 2, thal: 7,
};

const labels = {
  age: "Age", sex: "Sex (1=male, 0=female)", cp: "Chest pain type (1-4)",
  trestbps: "Resting BP", chol: "Cholesterol", fbs: "Fasting sugar >120 (1/0)",
  restecg: "Resting ECG (0-2)", thalach: "Max heart rate",
  exang: "Exercise angina (1/0)", oldpeak: "ST depression",
  slope: "ST slope (1-3)", thal: "Thal (3, 6 or 7)",
};

export default function App() {
  const [form, setForm] = useState(initial);
  const [result, setResult] = useState(null);
  const [history, setHistory] = useState([]);
  const [compare, setCompare] = useState({});
  const [baselines, setBaselines] = useState({});
  const [flp, setFlp] = useState({});
  const [error, setError] = useState("");

  const load = async () => {
    try {
      setHistory(await (await fetch(`${API}/history`)).json());
      setCompare(await (await fetch(`${API}/compare`)).json());
      setBaselines(await (await fetch(`${API}/baselines`)).json());
      setFlp(await (await fetch(`${API}/fl-process`)).json());
    } catch {
      setError(
        "Cannot reach the backend. If it is hosted on Render's free plan, wait 60 seconds and refresh."
      );
    }
  };
  useEffect(() => { load(); }, []);

  const submit = async (e) => {
    e.preventDefault();
    setError("");
    try {
      const body = Object.fromEntries(
        Object.entries(form).map(([k, v]) => [k, Number(v)])
      );
      const res = await fetch(`${API}/predict`, {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify(body),
      });
      if (!res.ok) throw new Error("Invalid input");
      setResult(await res.json());
      load();
    } catch {
      setError("Prediction failed. Check the values and that the backend is running.");
    }
  };

  const downloadReport = () => {
    if (!result) return;
    const lines = [
      "HEART ATTACK RISK REPORT",
      `Date: ${new Date().toLocaleString()}`,
      `Model: ${result.model} (federated learning, 4 hospitals)`,
      "",
      ...Object.entries(form).map(([k, v]) => `${k}: ${v}`),
      "",
      `Risk: ${result.risk}`,
      `Probability: ${(result.probability * 100).toFixed(1)}%`,
      `Binary output: ${result.binary}`,
      "",
      "Generated by a federated learning model. Educational use only, not a medical diagnosis.",
    ];
    const blob = new Blob([lines.join("\n")], { type: "text/plain" });
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = "risk_report.txt";
    a.click();
  };

  return (
    <div style={{ maxWidth: 860, margin: "30px auto", padding: "0 16px", fontFamily: "sans-serif" }}>
      <h1>Federated Heart Attack Risk Prediction</h1>
      <p>
        Trained across 4 hospitals with Flower (FedAvg, FedProx, FedCurv).
        Patient data never leaves its hospital.
      </p>

      <form onSubmit={submit}
        style={{ display: "grid", gridTemplateColumns: "1fr 1fr", gap: 10 }}>
        {Object.keys(initial).map((k) => (
          <label key={k}>
            {labels[k]}
            <input type="number" step="any" required value={form[k]}
              style={{ width: "100%", padding: 6, boxSizing: "border-box" }}
              onChange={(e) => setForm({ ...form, [k]: e.target.value })} />
          </label>
        ))}
        <button type="submit" style={{ gridColumn: "span 2", padding: 10, cursor: "pointer" }}>
          Predict
        </button>
      </form>

      {error && <p style={{ color: "crimson" }}>{error}</p>}

      {result && (
        <div>
          <h2 style={{ color: result.binary ? "crimson" : "green" }}>
            {result.risk} Risk: {(result.probability * 100).toFixed(1)}% (output: {result.binary})
          </h2>
          <p>Model used: {result.model}</p>
          <button onClick={downloadReport} style={{ padding: 8, cursor: "pointer" }}>
            Download report
          </button>
        </div>
      )}

      <FLProcess data={flp} baselines={baselines} />
      <Baselines data={baselines} />
      <Charts compare={compare} />

      <h3>Prediction history</h3>
      <table border="1" cellPadding="6" style={{ width: "100%", borderCollapse: "collapse" }}>
        <thead>
          <tr><th>Time</th><th>Age</th><th>Probability</th><th>Risk</th></tr>
        </thead>
        <tbody>
          {history.map((h) => (
            <tr key={h.id}>
              <td>{h.created}</td>
              <td>{h.inputs.age}</td>
              <td>{(h.probability * 100).toFixed(1)}%</td>
              <td style={{ color: h.binary ? "crimson" : "green" }}>{h.risk}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </div>
  );
}